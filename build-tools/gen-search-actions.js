// 生成 lib/search-browser-actions.js（write 工具对已删文件有守卫，改用生成脚本）
const fs = require('fs');
const lines = [];
lines.push("'use strict';");
lines.push('');
lines.push('/**');
lines.push(' * 搜索页浏览器动作。本文件随 lib/ 原样发布、不参与根目录混淆，');
lines.push(' * 保证 page.evaluate 序列化后的函数自包含（不含混淆作用域引用）。');
lines.push(' * 定位优先使用平台稳定的 data-e2e 标识，再退回占位文案匹配。');
lines.push(' */');
lines.push('');
lines.push('function findSearchInputRect() {');
lines.push('  let input = document.querySelector(\'input[data-e2e="searchbar-input"]\');');
lines.push('  if (!input || input.offsetParent === null) {');
lines.push("    input = Array.from(document.querySelectorAll('input')).find(el => el.offsetParent !== null && /搜索你感兴趣的内容|搜索/.test(el.getAttribute('placeholder') || '')) || null;");
lines.push('  }');
lines.push('  if (!input) return null;');
lines.push('  const r = input.getBoundingClientRect();');
lines.push('  return { x: r.x + r.width / 2, y: r.y + r.height / 2 };');
lines.push('}');
lines.push('');
lines.push('function openSearchEntry() {');
lines.push('  const button = document.querySelector(\'button[data-e2e="searchbar-button"]\');');
lines.push('  if (button && button.offsetParent !== null) { button.click(); return true; }');
lines.push("  const span = Array.from(document.querySelectorAll('span')).find(e => (e.textContent || '').trim() === '搜索' && e.offsetParent !== null);");
lines.push('  if (span) { span.click(); return true; }');
lines.push('  return false;');
lines.push('}');
lines.push('');
lines.push('function clickSearchTab(label) {');
lines.push("  const els = Array.from(document.querySelectorAll('div,span,a')).filter(e => (e.textContent || '').trim() === label && e.offsetParent !== null);");
lines.push('  if (els[0]) els[0].click();');
lines.push('  return !!els[0];');
lines.push('}');
lines.push('');
lines.push('module.exports = { findSearchInputRect, openSearchEntry, clickSearchTab };');
lines.push('');
fs.writeFileSync('D:/B1-抖音获客/dy-lead-app/lib/search-browser-actions.js', lines.join('\n'), 'utf-8');
console.log('created, length=', lines.join('\n').length);
