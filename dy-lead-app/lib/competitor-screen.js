'use strict';
/**
 * 同行 / 服务商识别：在 AI 判断与触达之前先排除。
 *
 * 依据 2026-10-21 实测采集（亚马逊停用/申诉/扫号/描述不符类作品）：近 3 天评论里约一半来自同行服务商，
 * 典型特征是“昵称带服务身份”或“评论是揽客话术”，而真实卖家的评论在讲自己的问题、问价格或问怎么联系。
 * 规则只做“明确是同行”的判定；拿不准的交给 AI，不在这里猜。
 */

// 昵称中的服务身份（命中即判同行）。“跨境”单独出现不算，卖家也常用。
const NICKNAME_SERVICE = [
  /申诉/, /服务商/, /代运营/, /店铺转让/, /收(?:店铺|号|店)/, /(?:出|卖)号/, /清库存/, /海外仓/, /货代/, /物流/, /国际快递/,
  /美工/, /合规/, /本土店/, /解封/, /激活/, /视频认证/, /KYC/i, /资金(?:申诉|解冻|出款)/, /取款/, /工作室/, /团队/, /商标/, /专利/, /财税/,
  /(?:跨境|亚马逊|AMZ)[^ ]{0,6}(?:服务|顾问|咨询|老师|助手|小助理)/i, /单号/
];

// 评论里的揽客 / 广告话术（命中即判同行）。
const TEXT_SOLICIT = [
  /^可以处理/, /可以(?:接|做|帮你处理)(?![么吗嘛？?])/,
  // “能接”是同行接单；“能接么/能接吗？”是卖家在问（实测：视频失败，能接么 → 真实需求）
  /能接(?![么吗嘛？?])/,
  // 收/出店铺、账号的买卖方
  /(?:回收|收|出)(?:店铺|店|号)(?![么吗嘛？?])/, /出号吗/, /(?:找我|私我|滴滴|dd我|扣我|加我|看主页|主页有|戳我|私信我)/i,
  /有需要(?:的)?(?:可以|随时|欢迎)/, /欢迎(?:咨询|滴滴|私信)/, /包过/, /保过/, /题库/, /已经(?:完全)?突破/, /专业(?:处理|团队|申诉)/,
  /成功率/, /(?:我们|我这边)(?:可以|能)(?:处理|做|接|帮)/, /同行勿扰/, /需要的(?:找|联系)/
];

function competitorReason(lead = {}) {
  const nickname = String(lead.nickname || '');
  const text = String(lead.demand || lead.text || '').trim();
  const nick = NICKNAME_SERVICE.find(pattern => pattern.test(nickname));
  if (nick) return `同行/服务商：昵称含“${nickname.match(nick)[0]}”`;
  const solicit = TEXT_SOLICIT.find(pattern => pattern.test(text));
  if (solicit) return `同行/服务商：评论为揽客话术“${text.match(solicit)[0]}”`;
  return '';
}

module.exports = { competitorReason, NICKNAME_SERVICE, TEXT_SOLICIT };
